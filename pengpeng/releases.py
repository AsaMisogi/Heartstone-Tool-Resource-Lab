def release_reference(cardid, cardsets, hero):
    """优先保留独立英雄的真实已知日期，其余卡牌取已知系列最早上线日。

    核心、传承和皮肤系列跨越多个年份，不能统一赋予系列建立日期。
    因此不在日历中的系列不会参与计算，也不会回退到 DBF ID。
    """
    if hero:
        if cardid in {f'HERO_{i:02}' for i in range(1, 10)}:
            return '2014-03-11', '基础英雄 · 游戏正式上线'
        return None, '日期未知'
    dates = [SET_RELEASES[sid] for sid in cardsets if sid in SET_RELEASES]
    return (min(dates), '系列上线日期（参考）') if dates else (None, '日期未知')
